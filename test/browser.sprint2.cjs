// Opt-in local browser smoke test; point only at a disposable Wrangler database.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const origin=process.env.E2E_ORIGIN||'http://127.0.0.1:8790';
  await page.goto(origin+'/');
  await page.locator('#nickname').fill('test_'+Date.now());
  await page.locator('#password').fill('example-pass-123');
  await page.locator('#btn-play').click();
  await page.waitForFunction(()=>document.querySelector('#auth-error').textContent.includes('註冊成功'));
  await page.getByRole('button',{name:'登入',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('#rows tr').length===6);
  await page.waitForFunction(()=>document.querySelectorAll('[data-chart-symbol]').length===6);
  await page.waitForFunction(()=>document.querySelectorAll('#book tr').length===5);
  assert((await page.locator('#rows').textContent()).includes('右鍵'));
  assert(!(await page.locator('#rows').textContent()).includes('2330'));
  assert(!(await page.locator('body').textContent()).includes('Cloudflare Worker'));
  assert(await page.locator('#page-market').isVisible());
  assert(!(await page.locator('#page-trade').isVisible()));
  await page.getByRole('button',{name:'下單',exact:true}).click();
  assert(await page.locator('#page-trade').isVisible());
  assert(!(await page.locator('#page-market').isVisible()));
  const before=await (await page.request.get(origin+'/api/account?id=1')).json();
  const stock=page.locator('#rows tr').filter({hasText:'GG'});
  await stock.getByRole('button',{name:'GG 買進'}).click();
  await page.getByLabel('交易股數').fill('10');
  await page.getByRole('button',{name:'確認買進'}).click();
  await page.waitForFunction(()=>document.querySelector('#msg').textContent.includes('成交 10 股'));
  await page.waitForFunction(()=>document.querySelector('#holdings').textContent.includes('GG'));
  const after=await (await page.request.get(origin+'/api/account?id=1')).json();
  assert.equal(after.holdings.find(h=>h.symbol==='2330').shares,(before.holdings.find(h=>h.symbol==='2330')?.shares||0)+10);
  assert(after.account.cash<before.account.cash);
  await page.waitForFunction(()=>!document.querySelector('#msg').textContent.includes('成交 10 股') || document.querySelector('#msg').className==='');
  await stock.getByRole('button',{name:'GG 賣出'}).click();
  await page.getByLabel('交易股數').fill('10');
  await page.getByRole('button',{name:'確認賣出'}).click();
  await page.waitForFunction(()=>document.querySelector('#msg').textContent.includes('成交 10 股')&&document.querySelector('#msg').className.includes('show'));
  await page.waitForFunction(()=>!document.querySelector('#holdings').textContent.includes('GG'));
  const result=await (await page.request.get(origin+'/api/account?id=1')).json();
  assert.equal(result.holdings.find(h=>h.symbol==='2330')?.shares||0,before.holdings.find(h=>h.symbol==='2330')?.shares||0);
  await page.waitForSelector('[data-chart-symbol="2330"] polyline',{state:'attached'});
  // 限價必須落在當日 ±10% 區間內才會被接受，且要低於最低賣價才會留在掛單中等待撮合。
  // 行情每分鐘都會變動，所以價格要從即時報價算出來，不能寫死。
  const stocks=(await (await page.request.get(origin+'/api/stocks')).json()).stocks;
  const yzu=stocks.find(s=>s.symbol==='YZU');
  assert(yzu && Number.isFinite(Number(yzu.ref_price)),'缺少 YZU 參考價');
  const refCents=Math.round(Number(yzu.ref_price)*100);
  const limitCents=Math.ceil(refCents*0.9);
  const feeCents=Math.ceil(limitCents*1425/1000000);
  const expectedFrozen=((limitCents+feeCents)*2/100).toLocaleString('zh-TW',{minimumFractionDigits:2,maximumFractionDigits:2});
  await page.locator('#rows tr').filter({hasText:'元智 AI'}).getByRole('button',{name:'元智 AI 買進'}).click();
  await page.locator('#trade-type').selectOption('LIMIT');
  await page.getByLabel('交易股數').fill('2');
  await page.getByLabel('每股限價').fill(String(limitCents/100));
  await page.getByRole('button',{name:'確認買進'}).click();
  await page.waitForFunction(()=>document.querySelector('#orders').textContent.includes('等待成交'));
  assert((await page.locator('#available').textContent()).includes('凍結 ' + expectedFrozen));
  await page.locator('#orders tr').filter({hasText:'等待成交'}).getByRole('button',{name:'取消'}).click();
  await page.getByRole('button',{name:'確認取消委託'}).click();
  await page.waitForFunction(()=>!document.querySelector('#orders').textContent.includes('等待成交'));
  assert((await page.locator('#available').textContent()).includes('凍結 0'));
  const smallStock=page.locator('#rows tr').filter({hasText:'元智 AI'});
  const existingSmall=(await (await page.request.get(origin+'/api/account?id=1')).json()).holdings.find(h=>h.symbol==='YZU')?.shares || 0;
  for(let i=0;i<2;i++){
   await smallStock.getByRole('button',{name:'元智 AI 買進'}).click();
   await page.getByLabel('交易股數').fill('1');
   await page.getByRole('button',{name:'確認買進'}).click();
   await page.waitForFunction(expected=>document.querySelector('#holdings').textContent.includes('元智 AI') && [...document.querySelectorAll('#holdings tr')].some(row=>row.textContent.includes('元智 AI') && row.cells[1].textContent.trim()===String(expected)),existingSmall+i+1);
  }
  await page.waitForSelector('[data-chart-symbol="YZU"] polyline',{state:'attached'});
  assert.equal(await page.locator('[data-chart-symbol]').count(),6);
  assert(await page.locator('[data-chart-symbol="2330"] polyline').count());
  await stock.getByRole('button',{name:'GG 買進'}).click();
  await page.getByLabel('交易股數').fill('10000000');
  await page.getByRole('button',{name:'確認買進'}).click();
  await page.waitForFunction(()=>document.querySelector('#trade-error').textContent.includes('不足'));
  assert(await page.locator('#trade-dialog').evaluate(el=>el.open));
  await page.locator('#cancel-trade').click();
  await page.getByRole('button',{name:'排行榜',exact:true}).click();
  assert(await page.locator('#page-ranking').isVisible());
  await page.getByRole('button',{name:'我的資產',exact:true}).click();
  assert(await page.locator('#page-holdings').isVisible());
  await page.locator('#filter-side').selectOption('BUY');
  await page.locator('#filter-apply').click();
  await page.waitForFunction(()=>[...document.querySelectorAll('#trades tr .tag')].every(tag=>tag.textContent==='買進'));
  assert.deepEqual(errors,[]);
  console.log('PASS: Chrome shows six stocks and book; actual buy/sell updates D1 account and UI without exceptions');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
